const { chromium } = require('playwright');
const { makeDb, handle, BASE } = require('./supabase-mock.js');
(async () => {
  const db = makeDb();
  const b = await chromium.launch();
  const ctx = await b.newContext({ viewport: { width: 390, height: 844 } });
  await ctx.route(`${BASE}/**`, (r) => handle(db, r));
  await ctx.route('https://**open-meteo.com/**', (r) => r.fulfill({ contentType: 'application/json', body: JSON.stringify({ current: { temperature_2m: 29, weather_code: 0, wind_speed_10m: 10, wind_direction_10m: 0 }, daily: { sunset: ['x T20:41'] } }) }));
  await ctx.route('https://fonts.googleapis.com/**', (r) => r.fulfill({ contentType: 'text/css', body: '' }));
  const p = await ctx.newPage();
  const errs = [];
  p.on('pageerror', (e) => errs.push(e.message));
  await p.goto('http://localhost:3030/?invite=' + 'a'.repeat(36));
  await p.waitForTimeout(2500);
  await p.evaluate(() => navigator.serviceWorker.ready);
  await p.reload();
  await p.waitForTimeout(2000);
  await ctx.setOffline(true);
  await p.reload();
  await p.waitForTimeout(3000);
  const h1 = await p.locator('.hero h1').textContent().catch(() => null);
  const banner = await p.locator('#offline').isVisible();
  console.log('offline headline:', h1, '| offline banner:', banner, '| errors:', errs);
  await p.goto('http://localhost:3030/#/dining');
  await p.waitForTimeout(1500);
  console.log('offline dining has menu:', await p.locator('text=Sea bass').count());
  await p.screenshot({ path: require('path').join(__dirname, 'offline.png') });
  await b.close();
})();
